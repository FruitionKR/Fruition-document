-- 사용자별 업로드 한도(UploadLimitService). 저장 용량은 documents·document_assets·meetings의 바이트 합으로 계산하고,
-- 하루 업로드 개수는 아래 기록 테이블로 센다. 원본 행이 삭제돼도 그날 올린 개수는 줄지 않아야 하므로 별도 기록을 둔다.
-- 기존 테이블 인덱스는 CONCURRENTLY가 필요해 V87로 나눈다. 새 테이블의 인덱스는 같은 트랜잭션에서 만든 빈 테이블이라
-- 다른 세션과 잠금을 다투지 않으므로 여기서 함께 만든다.
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS user_upload_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      VARCHAR(255) NOT NULL,
    workspace_id VARCHAR(255) NOT NULL,
    kind         VARCHAR(32)  NOT NULL CHECK (kind IN ('document', 'document_asset', 'meeting_recording')),
    byte_size    BIGINT       NOT NULL CHECK (byte_size >= 0),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_user_upload_events_user_created ON user_upload_events (user_id, created_at);
