-- 사용자별 업로드 한도(UploadLimitService). 저장 용량은 documents·document_assets·meetings의 바이트 합으로 계산하고,
-- 하루 업로드 개수는 아래 기록 테이블로 센다. 원본 행이 삭제돼도 그날 올린 개수는 줄지 않아야 하므로 별도 기록을 둔다.
CREATE TABLE user_upload_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      VARCHAR(255) NOT NULL,
    workspace_id VARCHAR(255) NOT NULL,
    kind         VARCHAR(32)  NOT NULL CHECK (kind IN ('document', 'document_asset', 'meeting_recording')),
    byte_size    BIGINT       NOT NULL CHECK (byte_size >= 0),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_user_upload_events_user_created ON user_upload_events (user_id, created_at);

-- 업로드마다 사용자 한 명의 사용량을 합산한다. 합산 대상 열을 INCLUDE해 index-only scan으로 끝나게 한다.
CREATE INDEX idx_documents_user_bytes ON documents (user_id) INCLUDE (byte_size);
CREATE INDEX idx_document_assets_uploader_bytes ON document_assets (uploaded_by) INCLUDE (byte_size);
CREATE INDEX idx_meetings_creator_recording_bytes ON meetings (created_by) INCLUDE (recording_bytes)
    WHERE recording_key IS NOT NULL;
